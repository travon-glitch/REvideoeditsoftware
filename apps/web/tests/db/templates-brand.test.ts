/*
 * STAGE 11 (database layer): brand kit (Super Admin), branding rules (administrators),
 * agent profiles, listing agent assignment, template approval / disable / defaults.
 */
import { randomUUID } from "node:crypto";
import type { PGlite } from "@electric-sql/pglite";
import { beforeAll, describe, expect, it } from "vitest";
import { company, freshDatabase, rejects, server, signedIn, type Session } from "./helpers";

let db: PGlite;
let org = "", org2 = "";
let ids: Record<string, string> = {}, ids2: Record<string, string> = {};
let owner: Session, adam: Session, alice: Session, vera: Session, worker: Session, other: Session;

beforeAll(async () => {
  db = await freshDatabase();
  const c = await company(db, { adam: "admin", alice: "editor", vera: "viewer" });
  org = c.org; ids = c.ids;
  owner = signedIn(db, ids.superAdmin!); adam = signedIn(db, ids.adam!); alice = signedIn(db, ids.alice!); vera = signedIn(db, ids.vera!); worker = server(db);
  // a second company (separate database harness user ids)
  const c2 = await secondCompany();
  org2 = c2.org; ids2 = c2.ids; other = signedIn(db, ids2.boss!);
});

async function secondCompany() {
  const boss = randomUUID();
  await db.query(`insert into auth.users (id, email) values ($1, 'boss@other.test')`, [boss]);
  const o = (await worker((tx) => tx.query<{ id: string }>(`insert into public.organizations (name, slug) values ('Other Realty', 'other') returning id`))).rows[0]!.id;
  await worker((tx) => tx.query(`insert into public.profiles (id, organization_id, email, full_name, role, status) values ($1, $2, 'boss@other.test', 'Boss', 'super_admin', 'active')`, [boss, o]));
  return { org: o, ids: { boss } };
}

describe("brand kit", () => {
  it("only the Super Admin changes it; everyone in the company reads it", async () => {
    expect((await adam((tx) => tx.query(`update public.brand_kits set intro_style = 'bar-wipe' returning 1`))).rows).toHaveLength(0);
    expect((await owner((tx) => tx.query(`update public.brand_kits set intro_style = 'bar-wipe', outro_style = 'agent-card', agent_layout = 'centered',
      brokerage_name = 'Acme Brokers LLC', brokerage_license = 'Lic. 99', music_mood = 'warm' returning 1`))).rows).toHaveLength(1);
    const r = await vera((tx) => tx.query<{ intro_style: string; brokerage_name: string }>(`select intro_style, brokerage_name from public.brand_kits`));
    expect(r.rows).toEqual([{ intro_style: "bar-wipe", brokerage_name: "Acme Brokers LLC" }]);
    expect((await other((tx) => tx.query(`select 1 from public.brand_kits where organization_id = $1`, [org]))).rows).toHaveLength(0);
  });
  it("a required disclosure needs text; styles are checked; logos stay in the company's folder", async () => {
    await rejects(owner((tx) => tx.query(`update public.brand_kits set disclaimer = null, disclosure_required = true`)), /brand_kits_disclosure_text/);
    await owner((tx) => tx.query(`update public.brand_kits set disclaimer = 'Acme Realty. Equal Housing Opportunity.', disclosure_required = true`));
    await rejects(owner((tx) => tx.query(`update public.brand_kits set intro_style = 'explode'`)));
    await rejects(owner((tx) => tx.query(`update public.brand_kits set brokerage_logo_path = $1`, [`${org2}/brand/x.png`])), /brand_kits_logo_paths/);
  });
  it("default music must be a verified track of the company", async () => {
    const asset = (await worker((tx) => tx.query<{ id: string }>(`insert into public.media_assets (organization_id, kind, bucket, storage_path, file_name, mime_type, size_bytes)
      values ($1, 'audio', 'music-library', $2, 'a.m4a', 'audio/mp4', 1) returning id`, [org, `${org}/music/${randomUUID()}.m4a`]))).rows[0]!.id;
    await rejects(owner((tx) => tx.query(`update public.brand_kits set music_asset_id = $1`, [asset])), /verified track/);
    await worker((tx) => tx.query(`insert into public.music_tracks (organization_id, asset_id, title, mood, license_type, license_details, commercial_use_verified, verified_at, builtin_key)
      values ($1, $2, 'Warm Welcome', 'warm', 'original_builtin', 'Original music generated by the app', true, now(), 'warm-welcome')`, [org, asset]));
    await owner((tx) => tx.query(`update public.brand_kits set music_asset_id = $1`, [asset]));
  });
});

describe("branding rules", () => {
  it("administrators set them; everyone who makes videos can read them", async () => {
    await rejects(alice((tx) => tx.query(`select public.admin_set_brand_rules(true, true, true, false, false)`)), /Only administrators/);
    await adam((tx) => tx.query(`select public.admin_set_brand_rules(true, true, true, true, false)`));
    const r = await alice((tx) => tx.query<{ r: Record<string, boolean> }>(`select public.my_brand_rules() r`));
    expect(r.rows[0]!.r).toEqual({ require_logo: true, require_disclosure: true, require_agent_card: true, lock_fonts: true, lock_colors: false });
    const audit = await owner((tx) => tx.query(`select 1 from public.audit_log where action = 'branding.rules'`));
    expect(audit.rows.length).toBeGreaterThan(0);
  });
});

describe("agent profiles", () => {
  let agentId = "", headshot = "";
  it("administrators create them; the headshot must be a company headshot", async () => {
    await rejects(alice((tx) => tx.query(`insert into public.agent_profiles (organization_id, name, created_by) values ($1, 'Alice', auth.uid())`, [org])), /row-level security/);
    headshot = (await adam((tx) => tx.query<{ id: string }>(`insert into public.media_assets (organization_id, uploaded_by, kind, bucket, storage_path, file_name, mime_type, size_bytes, width, height)
      values ($1, auth.uid(), 'headshot', 'brand-assets', $2, 'alice.jpg', 'image/jpeg', 100, 600, 800) returning id`, [org, `${org}/agents/${randomUUID()}.jpg`]))).rows[0]!.id;
    // a headshot outside the agents folder is refused
    await rejects(adam((tx) => tx.query(`insert into public.media_assets (organization_id, uploaded_by, kind, bucket, storage_path, file_name, mime_type, size_bytes)
      values ($1, auth.uid(), 'headshot', 'brand-assets', $2, 'x.jpg', 'image/jpeg', 1)`, [org, `${org}/brand/${randomUUID()}.jpg`])), /media_assets_headshot_folder/);
    const logo = (await adam((tx) => tx.query<{ id: string }>(`insert into public.media_assets (organization_id, uploaded_by, kind, bucket, storage_path, file_name, mime_type, size_bytes)
      values ($1, auth.uid(), 'logo', 'brand-assets', $2, 'l.png', 'image/png', 1) returning id`, [org, `${org}/brand/${randomUUID()}.png`]))).rows[0]!.id;
    await rejects(adam((tx) => tx.query(`insert into public.agent_profiles (organization_id, name, headshot_asset_id, created_by) values ($1, 'Alice', $2, auth.uid())`, [org, logo])), /headshot/);
    agentId = (await adam((tx) => tx.query<{ id: string }>(`insert into public.agent_profiles (organization_id, user_id, name, title, phone, email, brokerage, license, headshot_asset_id, created_by)
      values ($1, $2, 'Alice Agent', 'Listing Agent', '555-0100', 'alice@acme.test', 'Acme Realty', 'Lic. 0123', $3, auth.uid()) returning id`, [org, ids.alice, headshot]))).rows[0]!.id;
    await rejects(adam((tx) => tx.query(`insert into public.agent_profiles (organization_id, name, email, created_by) values ($1, 'Bad', 'not-an-email', auth.uid())`, [org])));
  });
  it("an agent edits their own contact details but can't switch the profile off or re-link it", async () => {
    expect((await alice((tx) => tx.query(`update public.agent_profiles set phone = '555-0199' where id = $1 returning 1`, [agentId]))).rows).toHaveLength(1);
    await rejects(alice((tx) => tx.query(`update public.agent_profiles set is_active = false where id = $1`, [agentId])), /Only administrators/);
    await rejects(alice((tx) => tx.query(`update public.agent_profiles set user_id = $2 where id = $1`, [agentId, ids.vera])), /Only administrators/);
    expect((await vera((tx) => tx.query(`update public.agent_profiles set phone = 'x' where id = $1 returning 1`, [agentId]))).rows).toHaveLength(0);
    expect((await other((tx) => tx.query(`select 1 from public.agent_profiles where id = $1`, [agentId]))).rows).toHaveLength(0);
  });
  it("listings are assigned an active agent of the same company", async () => {
    const listing = (await alice((tx) => tx.query<{ id: string }>(`insert into public.listings (organization_id, created_by, address_line) values ($1, auth.uid(), '742 Evergreen Terrace') returning id`, [org]))).rows[0]!.id;
    await alice((tx) => tx.query(`update public.listings set agent_profile_id = $1, previous_price = 560000, price = 525000 where id = $2`, [agentId, listing]));
    const foreign = (await other((tx) => tx.query<{ id: string }>(`insert into public.agent_profiles (organization_id, name, created_by) values ($1, 'Other Agent', auth.uid()) returning id`, [org2]))).rows[0]!.id;
    await rejects(alice((tx) => tx.query(`update public.listings set agent_profile_id = $1 where id = $2`, [foreign, listing])), /active agent/);
    await adam((tx) => tx.query(`update public.agent_profiles set is_active = false where id = $1`, [agentId]));
    await rejects(alice((tx) => tx.query(`update public.listings set agent_profile_id = null where id = $1`, [listing]).then(() =>
      tx.query(`update public.listings set agent_profile_id = $1 where id = $2`, [agentId, listing]))), /active agent/);
    await adam((tx) => tx.query(`update public.agent_profiles set is_active = true where id = $1`, [agentId]));
  });
});

describe("templates", () => {
  let builtin = "", custom = "";
  const spec = JSON.stringify({ recipe: "just-listed", name: "Just Listed" });
  it("the server adds the company's built-in templates, approved", async () => {
    builtin = (await worker((tx) => tx.query<{ id: string }>(`insert into public.video_templates (organization_id, slug, name, description, usage, style, builtin_key, status, sort_order)
      values ($1, 'just-listed', 'Just Listed', 'd', 'Announce a new listing', $2::jsonb, 'just-listed', 'approved', 1) returning id`, [org, spec]))).rows[0]!.id;
    const r = await alice((tx) => tx.query<{ status: string; is_active: boolean }>(`select status, is_active from public.video_templates where id = $1`, [builtin]));
    expect(r.rows).toEqual([{ status: "approved", is_active: true }]);
  });
  it("administrators create drafts only; approving is stamped by the database", async () => {
    await rejects(alice((tx) => tx.query(`insert into public.video_templates (organization_id, slug, name, style, created_by) values ($1, 'mine', 'Mine', '{}', auth.uid())`, [org])), /row-level security/);
    await rejects(adam((tx) => tx.query(`insert into public.video_templates (organization_id, slug, name, style, created_by, status) values ($1, 'mine', 'Mine', '{}', auth.uid(), 'approved')`, [org])), /row-level security/);
    custom = (await adam((tx) => tx.query<{ id: string }>(`insert into public.video_templates (organization_id, slug, name, style, usage, created_by) values ($1, 'spring-listing', 'Spring Listing', $2::jsonb, 'Spring campaign', auth.uid()) returning id`, [org, spec]))).rows[0]!.id;
    // editors don't see drafts
    expect((await alice((tx) => tx.query(`select 1 from public.video_templates where id = $1`, [custom]))).rows).toHaveLength(0);
    expect((await alice((tx) => tx.query(`update public.video_templates set status = 'approved' where id = $1 returning 1`, [custom]))).rows).toHaveLength(0);
    await adam((tx) => tx.query(`update public.video_templates set status = 'approved' where id = $1`, [custom]));
    const r = await adam((tx) => tx.query<{ approved_by: string; approved_at: string | null }>(`select approved_by, approved_at from public.video_templates where id = $1`, [custom]));
    expect(r.rows[0]!.approved_by).toBe(ids.adam);
    expect(r.rows[0]!.approved_at).not.toBeNull();
    expect((await alice((tx) => tx.query(`select 1 from public.video_templates where id = $1`, [custom]))).rows).toHaveLength(1);
  });
  it("editing an approved template sends it back for approval", async () => {
    await adam((tx) => tx.query(`update public.video_templates set name = 'Spring Listing 2' where id = $1`, [custom]));
    const r = await adam((tx) => tx.query<{ status: string; approved_by: string | null }>(`select status, approved_by from public.video_templates where id = $1`, [custom]));
    expect(r.rows).toEqual([{ status: "draft", approved_by: null }]);
    await adam((tx) => tx.query(`update public.video_templates set status = 'approved' where id = $1`, [custom]));
  });
  it("defaults: approved templates only, one per listing type, moved by the assign function", async () => {
    await rejects(alice((tx) => tx.query(`select public.admin_set_template_default($1, '{for_sale}')`, [builtin])), /Only administrators/);
    await adam((tx) => tx.query(`select public.admin_set_template_default($1, '{for_sale,coming_soon}')`, [builtin]));
    await rejects(adam((tx) => tx.query(`update public.video_templates set default_for = '{for_sale}' where id = $1`, [custom])), /already the default/);
    await adam((tx) => tx.query(`select public.admin_set_template_default($1, '{for_sale}')`, [custom]));
    const r = await alice((tx) => tx.query<{ id: string; default_for: string }>(`select id, default_for::text from public.video_templates order by name`));
    expect(Object.fromEntries(r.rows.map((x) => [x.id, x.default_for]))).toEqual({ [builtin]: "{coming_soon}", [custom]: "{for_sale}" });
  });
  it("disabling hides a template from people who make videos and drops its defaults; built-ins can't be deleted", async () => {
    await adam((tx) => tx.query(`update public.video_templates set status = 'disabled' where id = $1`, [custom]));
    const r = await adam((tx) => tx.query<{ is_active: boolean; default_for: string }>(`select is_active, default_for::text from public.video_templates where id = $1`, [custom]));
    expect(r.rows).toEqual([{ is_active: false, default_for: "{}" }]);
    expect((await alice((tx) => tx.query(`select 1 from public.video_templates where id = $1`, [custom]))).rows).toHaveLength(0);
    await rejects(adam((tx) => tx.query(`select public.admin_set_template_default($1, '{sold}')`, [custom])), /Approve the template/);
    expect((await adam((tx) => tx.query(`delete from public.video_templates where id = $1 returning 1`, [builtin]))).rows).toHaveLength(0);
    expect((await adam((tx) => tx.query(`delete from public.video_templates where id = $1 returning 1`, [custom]))).rows).toHaveLength(1);
    await rejects(adam((tx) => tx.query(`update public.video_templates set builtin_key = 'x' where id = $1`, [builtin])), /moved or re-linked/);
    expect((await other((tx) => tx.query(`select 1 from public.video_templates where organization_id = $1`, [org]))).rows).toHaveLength(0);
  });
});
