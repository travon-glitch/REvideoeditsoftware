/*
 * STAGE 10 (database layer): licensed music library, batch shape/planner, generation allowance.
 */
import { randomUUID } from "node:crypto";
import type { PGlite } from "@electric-sql/pglite";
import { beforeAll, describe, expect, it } from "vitest";
import { company, freshDatabase, rejects, server, signedIn, type Session } from "./helpers";

let db: PGlite;
let org = "";
let ids: Record<string, string> = {};
let alice: Session, adam: Session, vera: Session, worker: Session;

async function audioAsset(as: Session, path: string, by = "auth.uid()") {
  return (await as((tx) => tx.query<{ id: string }>(
    `insert into public.media_assets (organization_id, uploaded_by, kind, bucket, storage_path, file_name, mime_type, size_bytes)
     values ($1, ${by}, 'audio', 'music-library', $2, 't.m4a', 'audio/mp4', 100) returning id`, [org, path]))).rows[0]!.id;
}

beforeAll(async () => {
  db = await freshDatabase();
  const c = await company(db, { adam: "admin", alice: "editor", vera: "viewer" });
  org = c.org; ids = c.ids;
  alice = signedIn(db, ids.alice!); adam = signedIn(db, ids.adam!); vera = signedIn(db, ids.vera!); worker = server(db);
});

describe("licensed music library", () => {
  let asset = "";
  it("admins add tracks with licence details; editors can't", async () => {
    await rejects(audioAsset(alice, `${org}/music/${randomUUID()}.m4a`));
    asset = await audioAsset(adam, `${org}/music/${randomUUID()}.m4a`);
    await rejects(adam((tx) => tx.query(`insert into public.media_assets (organization_id, uploaded_by, kind, bucket, storage_path, file_name, mime_type, size_bytes)
      values ($1, auth.uid(), 'audio', 'music-library', $2, 't.m4a', 'audio/mp4', 1)`, [org, `${org}/listings/x/y.m4a`])));
    await rejects(adam((tx) => tx.query(`insert into public.music_tracks (organization_id, asset_id, title, mood, license_type, license_details) values ($1, $2, 'T', 'calm', 'licensed', '')`, [org, asset])));
    await adam((tx) => tx.query(`insert into public.music_tracks (organization_id, asset_id, title, mood, license_type, license_details, license_url)
      values ($1, $2, 'Sunrise', 'calm', 'licensed', 'Standard commercial licence #123', 'https://example.com/licence')`, [org, asset]));
  });
  it("verification records who verified it; it can't be faked for someone else", async () => {
    await rejects(adam((tx) => tx.query(`update public.music_tracks set commercial_use_verified = true, verified_by = $1, verified_at = now() where asset_id = $2`, [ids.alice, asset])));
    await adam((tx) => tx.query(`update public.music_tracks set commercial_use_verified = true, verified_by = auth.uid(), verified_at = now() where asset_id = $1`, [asset]));
    const r = await vera((tx) => tx.query<{ title: string; commercial_use_verified: boolean }>(`select title, commercial_use_verified from public.music_tracks`));
    expect(r.rows).toEqual([{ title: "Sunrise", commercial_use_verified: true }]);
    expect((await vera((tx) => tx.query(`select id from public.media_assets where id = $1`, [asset]))).rows).toHaveLength(1);
  });
  it("built-in original tracks are added by the server and can't be changed or deleted by people", async () => {
    const path = `${org}/music/${randomUUID()}.m4a`;
    const builtin = (await worker((tx) => tx.query<{ id: string }>(`insert into public.media_assets (organization_id, kind, bucket, storage_path, file_name, mime_type, size_bytes)
      values ($1, 'audio', 'music-library', $2, 'b.m4a', 'audio/mp4', 1) returning id`, [org, path]))).rows[0]!.id;
    await worker((tx) => tx.query(`insert into public.music_tracks (organization_id, asset_id, title, mood, license_type, license_details, commercial_use_verified, verified_at, builtin_key)
      values ($1, $2, 'Calm Morning', 'calm', 'original_builtin', 'Original music generated by the app', true, now(), 'calm-morning')`, [org, builtin]));
    await rejects(adam((tx) => tx.query(`insert into public.music_tracks (organization_id, asset_id, title, mood, license_type, license_details) values ($1, $2, 'x', 'calm', 'original_builtin', 'abc')`, [org, builtin])));
    expect((await adam((tx) => tx.query(`update public.music_tracks set title = 'x' where builtin_key = 'calm-morning' returning 1`))).rows).toHaveLength(0);
    expect((await adam((tx) => tx.query(`delete from public.media_assets where id = $1 returning 1`, [builtin]))).rows).toHaveLength(0);
  });
  it("storage: everyone in the company reads library files; only admins upload", async () => {
    const path = `${org}/music/${randomUUID()}.m4a`;
    await rejects(alice((tx) => tx.query(`insert into storage.objects (bucket_id, name, owner_id) values ('music-library', $1, auth.uid()::text)`, [path])));
    await adam((tx) => tx.query(`insert into storage.objects (bucket_id, name, owner_id) values ('music-library', $1, auth.uid()::text)`, [path]));
    expect((await vera((tx) => tx.query(`select name from storage.objects where name = $1`, [path]))).rows).toHaveLength(1);
  });
});

describe("batches v2 and allowance", () => {
  it("records the shape and planner; AI planning needs AI access", async () => {
    const l = (await alice((tx) => tx.query<{ id: string }>(`insert into public.listings (organization_id, created_by) values ($1, auth.uid()) returning id`, [org]))).rows[0]!.id;
    const b = await alice((tx) => tx.query<{ aspect: string; planner: string }>(`select (b).aspect, (b).planner from (select public.start_video_batch($1, 6) b) s`, [l]));
    expect(b.rows[0]).toEqual({ aspect: "9:16", planner: "rules" });
    await worker((tx) => tx.query(`update public.profiles set can_use_ai = false where id = $1`, [ids.alice]));
    await rejects(alice((tx) => tx.query(`select public.start_video_batch($1, 6, '{}'::jsonb, '16:9', 'ai_director')`, [l])), /AI isn't switched on/);
    await worker((tx) => tx.query(`update public.profiles set can_use_ai = true where id = $1`, [ids.alice]));
  });
  it("tells a person their remaining limits without exposing company settings", async () => {
    await worker((tx) => tx.query(`update public.organization_settings set daily_video_limit = 10, max_batch_size = 6 where organization_id = $1`, [org]));
    const a = (await alice((tx) => tx.query<{ a: Record<string, unknown> }>(`select public.my_generation_allowance() a`))).rows[0]!.a;
    expect(a).toMatchObject({ can_batch: true, max_batch_size: 6, daily_limit: 10, used_today: 0, director_available: false });
    expect((await vera((tx) => tx.query<{ a: { can_batch: boolean } }>(`select public.my_generation_allowance() a`))).rows[0]!.a.can_batch).toBe(false);
  });
});
